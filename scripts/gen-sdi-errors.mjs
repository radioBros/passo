#!/usr/bin/env node
/**
 * Generate src/shared/errors/sdi-errors.ts from the official
 * "Elenco dei controlli" PDF (Agenzia delle Entrate).
 *
 * The catalogue is GENERATED rather than hand-written for the same reason the
 * FatturaPA enums are: 63 codes transcribed by hand will contain a typo, and a
 * wrong description attached to a real rejection sends an integrator hunting
 * the wrong field. Regenerate when AdE publishes a new Elenco.
 *
 *   node scripts/gen-sdi-errors.mjs [path-to-pdf]
 *
 * Requires python3 with pypdf for text extraction.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const pdf = process.argv[2] ?? 'assets/spec/Elenco-Controlli-versione-2.0.pdf';
const OUT = 'src/shared/errors/sdi-errors.ts';

const text = execFileSync('python3', ['-c', `
from pypdf import PdfReader
import sys
r = PdfReader(sys.argv[1])
sys.stdout.write("\\n".join((p.extract_text() or "") for p in r.pages))
`, pdf], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });

const re = /-\s*Codice\s+(00\d{3})\s+([\s\S]*?)(?=\s*-\s*Codice\s+00\d{3}|\n\s*\n)/g;
const codes = new Map();
for (const m of text.matchAll(re)) {
  const desc = m[2].replace(/\s+/g, ' ').trim().replace(/\.$/, '');
  if (!codes.has(m[1]) || desc.length > codes.get(m[1]).length) codes.set(m[1], desc);
}

// Every code that appears anywhere must be captured; a silent miss would leave
// a real rejection reason undescribed.
const seen = new Set([...text.matchAll(/\b(00\d{3})\b/g)].map((m) => m[1]));
const missed = [...seen].filter((c) => !codes.has(c));
if (missed.length) {
  console.error(`FAILED: codes present in the PDF but not captured: ${missed.join(', ')}`);
  process.exit(1);
}

/**
 * What the CRM must DO about a code — the part a raw number cannot express.
 * Ranges follow the Elenco's own grouping: 001xx signature, 003xx party
 * identifiers, 004xx document body.
 */
function remedyFor(code) {
  const c = Number(code);
  if (c === 1 || c === 2) return 'resubmit';
  if (c === 3) return 'split';
  if (c >= 100 && c <= 107) return 'signature';
  if (c === 409) return 'duplicate';
  if (c >= 300 && c <= 330) return 'fix_identifiers';
  return 'fix_payload';
}

/**
 * A short English gloss so an integrator who does not read Italian can triage
 * without a translation round-trip. The official Italian text is ALWAYS kept
 * verbatim beside it: the gloss is a convenience, never the authority, and it
 * deliberately does not paraphrase the element paths.
 */
const GLOSS = {
  resubmit: 'File naming or transport fault',
  split: 'File exceeds the channel size limit',
  signature: 'Digital signature rejected',
  duplicate: 'SdI already holds this invoice',
  fix_identifiers: 'A party identifier is invalid',
  fix_payload: 'An invoice field is missing, malformed or inconsistent',
};

const REMEDY_TEXT = {
  resubmit: 'A transport-level fault. PASSO retries with a corrected file name; no CRM action.',
  split: 'The file exceeds the channel size limit. Split the invoice or use a larger-capacity channel.',
  signature: 'The digital signature was rejected. A CRM cannot fix this — the signing certificate or the signing service must be corrected.',
  duplicate: 'SdI already holds an invoice with this seller, year and number. Do NOT resubmit; use a different number, or check whether the original was accepted.',
  fix_identifiers: 'A party identifier (VAT number, fiscal code, recipient code) is wrong. Correct it and issue a NEW invoice.',
  fix_payload: 'A field is missing, malformed or inconsistent. Correct it and issue a NEW invoice.',
};

const q = (v) => JSON.stringify(v);
const sorted = [...codes.keys()].sort();

const body = `/**
 * SdI rejection (NS) error catalogue — all ${sorted.length} codes.
 *
 * GENERATED by scripts/gen-sdi-errors.mjs from the official
 * "Elenco dei controlli" v2.0 (Agenzia delle Entrate). Do not edit by hand.
 *
 * An NS carries a bare code like "00423". Alone it tells a CRM nothing: the
 * integrator has to find an Italian-language PDF and read it. Since **NS is
 * terminal** — the invoice is legally NOT issued and needs a brand-new one with
 * a fresh ProgressivoInvio — the CRM must act on every one of these, and acting
 * requires knowing what went wrong.
 *
 * \`remedy\` is the part a raw code cannot express: what the CRM should DO. It
 * matters most for 00409 (duplicate), where the intuitive response —
 * resubmitting — is precisely wrong.
 *
 * Descriptions are the official Italian text, quoted verbatim rather than
 * translated: they name FatturaPA elements by their exact path and tag, and a
 * translation would break the correspondence to the schema. \`gloss\` is a short
 * English triage aid — a convenience, never the authority.
 */

export const SDI_CATALOGUE_SOURCE =
  'Agenzia delle Entrate — Elenco dei controlli v2.0';

export type SdiRemedy =
  ${Object.keys(REMEDY_TEXT).map((k) => q(k)).join(' | ')};

export interface SdiErrorInfo {
  /** The five-digit code exactly as SdI sends it. */
  code: string;
  /** Official Italian description from the Elenco dei controlli. */
  description: string;
  /** Short English triage aid. Never authoritative. */
  gloss: string;
  /** What the CRM should do about it. */
  remedy: SdiRemedy;
}

/** What each remedy means, in terms a CRM integrator can act on. */
export const REMEDY_GUIDANCE: Record<SdiRemedy, string> = {
${Object.entries(REMEDY_TEXT).map(([k, v]) => `  ${k}: ${q(v)},`).join('\n')}
};

export const SDI_ERRORS: Record<string, SdiErrorInfo> = {
${sorted.map((c) => {
  const r = remedyFor(c);
  return `  ${q(c)}: { code: ${q(c)}, description: ${q(codes.get(c))}, gloss: ${q(GLOSS[r])}, remedy: ${q(r)} },`;
}).join('\n')}
};

export const SDI_ERROR_COUNT = Object.keys(SDI_ERRORS).length;

/**
 * Describe a code SdI sent us.
 *
 * An UNKNOWN code is reported as unknown rather than swallowed: SdI adds codes
 * over time, and a catalogue that silently returns nothing would make a new
 * rejection reason invisible exactly when someone needs to see it.
 */
export function describeSdiError(code: string): SdiErrorInfo & { known: boolean } {
  const hit = SDI_ERRORS[code];
  if (hit) return { ...hit, known: true };
  return {
    code,
    description:
      \`Unknown SdI error code "\${code}". It is not in the Elenco dei controlli v2.0 \` +
      'bundled with this release — consult the current Agenzia delle Entrate ' +
      'documentation, and please report it so the catalogue can be updated.',
    gloss: 'Unknown code',
    remedy: 'fix_payload',
    known: false,
  };
}

/**
 * Enrich the codes from an NS into something a CRM can act on.
 *
 * SdI's own \`descrizione\` is sometimes present and sometimes null; the
 * catalogue fills the gap and, more importantly, adds the remedy. Keeping
 * SdI's text alongside ours means an integrator can always see what the tax
 * authority actually said — including for a code we do not know.
 */
export function enrichSdiErrors(
  errors: ReadonlyArray<{ codice: string; descrizione?: string | null }>,
): Array<SdiErrorInfo & { known: boolean; sdiDescription: string | null; guidance: string }> {
  return errors.map((e) => {
    const info = describeSdiError(e.codice);
    return {
      ...info,
      sdiDescription: e.descrizione ?? null,
      guidance: REMEDY_GUIDANCE[info.remedy],
    };
  });
}
`;

writeFileSync(OUT, body);
console.error(`wrote ${OUT}: ${sorted.length} codes from ${pdf}`);
